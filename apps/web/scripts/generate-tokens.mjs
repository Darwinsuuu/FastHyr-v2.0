// Generates styles/tokens.css from docs/design/tokens.json (the design system's source of truth).
// Run `pnpm --filter web tokens` after changing tokens.json; `--check` fails when the file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, "../../../docs/design/tokens.json");
const TARGET = resolve(here, "../styles/tokens.css");

// Styles the brand book sets in words rather than in tokens.json (DESIGN_SYSTEM.md §2).
const EXTRA_TYPE = { label: { textTransform: "uppercase" } };
// next/font exposes each family as a CSS variable (app/fonts.ts); tokens.json gives the fallbacks.
const FONT_VARIABLES = {
  display: "--font-fraunces",
  sans: "--font-hanken",
  mono: "--font-plex-mono",
};

export function buildTokensCss(tokens) {
  const colors = tokens.color.tokens;
  const vars = (theme) => colors.map((t) => `  --fh-${t.name}: ${t.value[theme]};`);
  const shadows = (theme) =>
    tokens.shadow.tokens.map((t) => `  --fh-${t.name}: ${t.value[theme]};`);
  const families = Object.entries(tokens.type.families);
  const styles = tokens.type.groups.flatMap((group) =>
    group.styles.map((style) => ({ ...style, family: group.family, ...EXTRA_TYPE[style.name] })),
  );

  const lines = [
    "/* Generated by scripts/generate-tokens.mjs from docs/design/tokens.json. Do not edit. */",
    "",
    "/* Paper (light) is the default; Night (dark) follows the system unless data-theme is set. */",
    ":root {",
    "  color-scheme: light;",
    ...vars("light"),
    ...shadows("light"),
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...vars("dark"),
    ...shadows("dark"),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    "    color-scheme: dark;",
    ...vars("dark").map((line) => `  ${line}`),
    ...shadows("dark").map((line) => `  ${line}`),
    "  }",
    "}",
    "",
    "/* Tailwind theme: bg-surface, text-ink, border-line, font-display, text-body-sm, rounded-md… */",
    "@theme inline {",
    ...colors.map((t) => `  --color-${t.name}: var(--fh-${t.name});`),
    ...families.map(([name, stack]) => `  --font-${name}: var(${FONT_VARIABLES[name]}), ${stack};`),
    ...styles.flatMap((s) => [
      `  --text-${s.name}: ${s.fontSize};`,
      `  --text-${s.name}--line-height: ${s.lineHeight};`,
      `  --text-${s.name}--font-weight: ${s.fontWeight};`,
      ...(s.letterSpacing ? [`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`] : []),
    ]),
    ...tokens.radius.tokens.map((t) => `  --radius-${t.name.replace("radius-", "")}: ${t.value};`),
    ...tokens.shadow.tokens.map(
      (t) => `  --shadow-${t.name.replace("shadow-", "")}: var(--fh-${t.name});`,
    ),
    "}",
    "",
    "/* Spacing needs no mapping: Tailwind's 4px scale already equals space-1…space-16 (p-4 = 16px). */",
    ":root {",
    ...tokens.spacing.tokens.map((t) => `  --fh-${t.name}: ${t.value};`),
    "}",
    "",
    "/* Full text styles, family included: `type-question`, `type-label`… */",
    ...styles.flatMap((s) => [
      `@utility type-${s.name} {`,
      `  font-family: var(--font-${s.family});`,
      `  font-size: var(--text-${s.name});`,
      `  line-height: var(--text-${s.name}--line-height);`,
      `  font-weight: var(--text-${s.name}--font-weight);`,
      ...(s.letterSpacing ? [`  letter-spacing: var(--text-${s.name}--letter-spacing);`] : []),
      ...(s.fontStyle ? [`  font-style: ${s.fontStyle};`] : []),
      ...(s.textTransform ? [`  text-transform: ${s.textTransform};`] : []),
      "}",
    ]),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = buildTokensCss(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== css) {
      console.error("styles/tokens.css is out of date: run `pnpm --filter web tokens`.");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, css);
    console.log("Wrote styles/tokens.css");
  }
}
