import createClient, { type Client } from "openapi-fetch";

import type { paths } from "./schema";

export type { components, paths } from "./schema";

export type ApiClient = Client<paths>;

export interface ApiClientOptions {
  baseUrl: string;
  /** The signed-in user's Supabase access token, or null when signed out. */
  getAccessToken?: () => Promise<string | null> | string | null;
  /** The active workspace (the `fh_ws` cookie) sent as `X-Workspace-Id` on TA endpoints. */
  getWorkspaceId?: () => Promise<string | null> | string | null;
  /** Override for tests. */
  fetch?: typeof globalThis.fetch;
}

/** An API error as problem+json (BACKEND.md §3). Show copy by `code`, never by `title`. */
export class ApiError extends Error {
  readonly status: number;
  readonly code: string;
  readonly requestId: string | undefined;
  readonly errors: unknown[] | undefined;

  constructor(status: number, code: string, title: string, requestId?: string, errors?: unknown[]) {
    super(title);
    this.name = "ApiError";
    this.status = status;
    this.code = code;
    this.requestId = requestId;
    this.errors = errors;
  }

  static from(response: Response, body: unknown): ApiError {
    const problem = (body && typeof body === "object" ? body : {}) as Record<string, unknown>;
    return new ApiError(
      response.status,
      typeof problem.code === "string" ? problem.code : "http_error",
      typeof problem.title === "string" ? problem.title : response.statusText,
      typeof problem.request_id === "string"
        ? problem.request_id
        : (response.headers.get("x-request-id") ?? undefined),
      Array.isArray(problem.errors) ? problem.errors : undefined,
    );
  }
}

/** Typed FastHyr API client. `schema.d.ts` is generated by `make api-client`. */
export function createApiClient(options: ApiClientOptions): ApiClient {
  const client = createClient<paths>({ baseUrl: options.baseUrl, fetch: options.fetch });
  client.use({
    async onRequest({ request }) {
      const token = await options.getAccessToken?.();
      if (token) {
        request.headers.set("Authorization", `Bearer ${token}`);
      }
      const workspaceId = await options.getWorkspaceId?.();
      if (workspaceId && !request.headers.has("X-Workspace-Id")) {
        request.headers.set("X-Workspace-Id", workspaceId);
      }
      return request;
    },
  });
  return client;
}

/** Returns `data`, or throws an `ApiError` (so TanStack Query sees a failure). */
export function unwrap<T>(result: { data?: T; error?: unknown; response: Response }): T {
  if (result.error !== undefined || !result.response.ok) {
    throw ApiError.from(result.response, result.error);
  }
  return result.data as T;
}
